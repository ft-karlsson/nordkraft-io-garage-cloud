//! The user's private container registry: its local config and the
//! `registry://name:tag` shorthand.

use reqwest::Client;
use serde::{Deserialize, Serialize};

use std::time::Duration;

use super::config::get_config_dir;

pub(crate) const REGISTRY_CONFIG_FILE: &str = "registry.json";

pub(crate) const REGISTRY_IMAGE: &str = "ghcr.io/ft-karlsson/oci-registry:0.2.0";

pub(crate) const REGISTRY_USERNAME: &str = "nordkraft";

#[derive(Debug, Deserialize, Serialize)]
pub(crate) struct RegistryConfig {
    pub(crate) address: String,
    pub(crate) container_name: String,
    pub(crate) container_alias: Option<String>,
    /// Basic-auth credentials, generated by `registry init` (0.2.0+). Registries created
    /// before that have none and stay open; destroy + init to get a protected one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub(crate) username: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub(crate) password: Option<String>,
}

/// 48 hex chars from the OS random source. No extra crate needed.
pub(crate) fn generate_registry_password() -> Result<String, Box<dyn std::error::Error>> {
    use std::io::Read;
    let mut bytes = [0u8; 24];
    std::fs::File::open("/dev/urandom")?.read_exact(&mut bytes)?;
    Ok(bytes.iter().map(|b| format!("{b:02x}")).collect())
}

/// GET against the private registry, with Basic auth when the registry has credentials.
pub(crate) fn registry_get(
    client: &Client,
    config: &RegistryConfig,
    path: &str,
) -> reqwest::RequestBuilder {
    let req = client
        .get(format!("http://{}{}", config.address, path))
        .timeout(Duration::from_secs(5));
    match (&config.username, &config.password) {
        (Some(user), Some(pass)) => req.basic_auth(user, Some(pass)),
        _ => req,
    }
}

pub(crate) fn load_registry_config() -> Option<RegistryConfig> {
    let path = get_config_dir().join(REGISTRY_CONFIG_FILE);
    if path.exists() {
        if let Ok(contents) = std::fs::read_to_string(&path) {
            if let Ok(config) = serde_json::from_str(&contents) {
                return Some(config);
            }
        }
    }
    None
}

pub(crate) fn save_registry_config(
    config: &RegistryConfig,
) -> Result<(), Box<dyn std::error::Error>> {
    let dir = get_config_dir();
    std::fs::create_dir_all(&dir)?;
    let path = dir.join(REGISTRY_CONFIG_FILE);
    std::fs::write(path, serde_json::to_string_pretty(config)?)?;
    Ok(())
}

pub(crate) fn remove_registry_config() {
    let path = get_config_dir().join(REGISTRY_CONFIG_FILE);
    let _ = std::fs::remove_file(path);
}

/// Resolve `registry://name:tag` to the user's private registry address.
/// Returns the resolved image string, or the original if not a registry:// reference.
pub(crate) fn resolve_registry_image(image: &str) -> Result<String, Box<dyn std::error::Error>> {
    if !image.starts_with("registry://") {
        return Ok(image.to_string());
    }
    let short_name = image.strip_prefix("registry://").unwrap();
    let reg_config = load_registry_config()
        .ok_or("Registry not initialized. Run 'nordkraft registry init' first.")?;
    Ok(format!("{}/{}", reg_config.address, short_name))
}
